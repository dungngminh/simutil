/// Unicode symbols used in the SimUtil TUI.
abstract class SimutilIcons {
  /// Running / on state indicator.
  static const String on = '●';

  /// Stopped / off state indicator.
  static const String off = '○';

  /// Selection pointer in menus.
  static const String pointer = '▸';

  /// Checked checkbox label.
  static const String checked = '[✓]';

  /// Unchecked checkbox label.
  static const String unchecked = '[ ]';

  /// Previous item in cyclic controls.
  static const String cycleLeft = '◂';

  /// Next item in cyclic controls.
  static const String cycleRight = '▸';
}
